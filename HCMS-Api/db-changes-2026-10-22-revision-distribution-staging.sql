-- Revision: Document Users / Distribution List are kept per version.
--
-- Until a revision is approved, the document's own list (DocumentRoleDistributions / DocumentUserDistributions)
-- must stay exactly as it is for the version in force. The list proposed by the revision is held here instead,
-- shown to the approver, and moved onto the document only when the revision becomes Effective.
--
--   DocumentRevisionDistributions      one row per document that has a revised list waiting (also when that
--                                      list is empty -- "no list" is a valid proposal)
--   DocumentRevisionRoleDistributions  same columns as DocumentRoleDistributions
--   DocumentRevisionUserDistributions  same columns as DocumentUserDistributions
--
-- Safe to run more than once. Nothing existing is changed or dropped.

CREATE TABLE IF NOT EXISTS DocumentRevisionDistributions (
    Id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CompanyId   INTEGER NOT NULL,
    DocumentId  INTEGER NOT NULL,
    CreatedAt   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy   VARCHAR NOT NULL,
    CONSTRAINT uq_documentrevisiondistributions UNIQUE (CompanyId, DocumentId)
);

CREATE TABLE IF NOT EXISTS DocumentRevisionRoleDistributions (
    Id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CompanyId           INTEGER NOT NULL,
    DocumentId          INTEGER NOT NULL,
    DivisionCode        VARCHAR,
    DepartmentCode      VARCHAR,
    SubDepartmentCode   VARCHAR,
    BusinessDomainCode  VARCHAR,
    RoleId              INTEGER NOT NULL,
    DistributionType    INTEGER NOT NULL,
    CreatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy           VARCHAR NOT NULL,
    IsRetrieved         BOOLEAN NOT NULL DEFAULT FALSE,
    RetrievedAt         TIMESTAMP,
    RetrievedBy         VARCHAR
);
CREATE INDEX IF NOT EXISTS ix_docrevroledist_doc ON DocumentRevisionRoleDistributions (CompanyId, DocumentId);

CREATE TABLE IF NOT EXISTS DocumentRevisionUserDistributions (
    Id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CompanyId           INTEGER NOT NULL,
    DocumentId          INTEGER NOT NULL,
    EmployeeCode        VARCHAR NOT NULL,
    CreatedAt           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy           VARCHAR NOT NULL,
    RoleId              INTEGER,
    DivisionCode        VARCHAR,
    DepartmentCode      VARCHAR,
    SubDepartmentCode   VARCHAR,
    BusinessDomainCode  VARCHAR
);
CREATE INDEX IF NOT EXISTS ix_docrevuserdist_doc ON DocumentRevisionUserDistributions (CompanyId, DocumentId);
